static_assert(!std::is_constructible_v<rebirths::Context, HMODULE, std::wstring, std::wstring>,
              "A patch context must name its game explicitly");
static_assert(std::is_constructible_v<rebirths::Context, HMODULE, const rebirths::GameSpec&,
                                    std::wstring, std::wstring>);

int main() {
    const rebirths::GameId ids[] = {
        rebirths::GameId::Rebirth1,
        rebirths::GameId::Rebirth2,
        rebirths::GameId::Rebirth3,
        rebirths::GameId::SegaHardGirls,
    };

    for (const rebirths::GameId id : ids) {
        const rebirths::GameSpec& spec = rebirths::GameSpecFor(id);
        const rebirths::Context context{nullptr, spec, L"patch directory", L"configuration"};
        assert(context.spec.id == id);
        assert(context.directory == L"patch directory" && context.ini == L"configuration");
        assert(spec.preferredImageBase == 0x00400000);
        assert(spec.textStartRva < spec.textEndRva);
        assert(rebirths::IdentifyGame(spec.executableSha256) == &spec);
        assert(rebirths::IdentifyGame(spec.executableSha256LargeAddressAware) == &spec);
        assert(rebirths::IdentifyGame(spec.executableSha256LargeAddressAwareWithChecksum) == &spec);
        assert(std::strcmp(rebirths::GameIdName(id), "unknown") != 0);
    }

    const rebirths::GameSpec& rebirth3 = rebirths::GameSpecFor(rebirths::GameId::Rebirth3);
    assert(rebirth3.executableSha256 == Rebirth3Baseline);
    assert(rebirth3.executableSha256LargeAddressAware == Rebirth3LargeAddressAware);
    assert(rebirth3.textStartRva == 0x00001000);
    assert(rebirth3.textEndRva == 0x00382800);
    assert(rebirths::IdentifyGame(Rebirth3Baseline) == &rebirth3);
    assert(rebirths::IdentifyGame(Rebirth3LargeAddressAware) == &rebirth3);

    constexpr rebirths::Digest Rebirth2Baseline = {
        0xf0,0xb0,0xb9,0xfe,0x40,0xa2,0x6a,0x00,0x1d,0x0a,0xc8,0x77,0x02,0xd5,0x18,0x44,
        0xf1,0x99,0x00,0xcf,0xab,0xe3,0xd3,0x86,0x80,0xb8,0x85,0xcc,0x60,0x7c,0x2f,0xb2};
    constexpr rebirths::Digest SegaHardGirlsBaseline = {
        0xaf,0x95,0x50,0xb0,0xb5,0xab,0x90,0x81,0x0e,0x31,0x27,0x40,0x66,0xf1,0x3b,0x3e,
        0x1b,0x22,0x4e,0xf5,0x96,0x09,0x51,0xa4,0x4d,0x2a,0xcd,0x53,0x90,0x35,0x23,0xe5};
    assert(rebirths::IdentifyGame(Rebirth2Baseline) == &rebirths::GameSpecFor(rebirths::GameId::Rebirth2));
    assert(rebirths::IdentifyGame(SegaHardGirlsBaseline) == &rebirths::GameSpecFor(rebirths::GameId::SegaHardGirls));
    assert(rebirths::GameSpecFor(rebirths::GameId::Rebirth1).executableSha256LargeAddressAware == Rebirth1LargeAddressAware);
    assert(rebirths::GameSpecFor(rebirths::GameId::Rebirth2).executableSha256LargeAddressAware == Rebirth2LargeAddressAware);
    assert(rebirths::GameSpecFor(rebirths::GameId::SegaHardGirls).executableSha256LargeAddressAware == SegaHardGirlsLargeAddressAware);
    assert(rebirths::IdentifyGame(Rebirth1LargeAddressAware) == &rebirths::GameSpecFor(rebirths::GameId::Rebirth1));
    assert(rebirths::IdentifyGame(Rebirth2LargeAddressAware) == &rebirths::GameSpecFor(rebirths::GameId::Rebirth2));
    assert(rebirths::IdentifyGame(SegaHardGirlsLargeAddressAware) == &rebirths::GameSpecFor(rebirths::GameId::SegaHardGirls));
    assert(rebirth3.executableSha256LargeAddressAwareWithChecksum == Rebirth3LargeAddressAwareWithChecksum);
    assert(rebirths::IdentifyGame(Rebirth3LargeAddressAwareWithChecksum) == &rebirth3);
    assert(rebirths::GameSpecFor(rebirths::GameId::Rebirth1).executableSha256LargeAddressAwareWithChecksum == Rebirth1LargeAddressAwareWithChecksum);
    assert(rebirths::GameSpecFor(rebirths::GameId::Rebirth2).executableSha256LargeAddressAwareWithChecksum == Rebirth2LargeAddressAwareWithChecksum);
    assert(rebirths::GameSpecFor(rebirths::GameId::SegaHardGirls).executableSha256LargeAddressAwareWithChecksum == SegaHardGirlsLargeAddressAwareWithChecksum);

    rebirths::Digest unknown{};
    assert(!rebirths::IdentifyGame(unknown));
    std::puts("target identity/spec dispatch tests passed");
    return 0;
}
